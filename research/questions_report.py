"""Write results/data/questions.md: every question Claude wrote, and which condition uses it.

    python research/questions_report.py

Reads data/answers/questions.csv (each question's precision, recall and F0.5 on train, as TRL
scored them) and the saved TRL models (data/models/*): C2's rules (the 40 Kev reads, best
first), the elastic nets' weights (C1a, C1a-40) and the vote's rules (C1b). Nothing is
recomputed; the page only lays out what the B1 fit produced.
"""

from __future__ import annotations

import argparse
import csv
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import ROOT  # noqa: E402


def weights(model) -> dict[str, float]:
    if getattr(model, "combiner_", None) is None:
        return {}
    return {q: float(c) for q, c in zip(model.rules_, model.combiner_.coef)}


def fmt(x: float | None) -> str:
    return "" if x is None else f"{x:+.2f}"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--answers", type=Path, default=ROOT / "data" / "answers")
    ap.add_argument("--models", type=Path, default=ROOT / "data" / "models")
    ap.add_argument("--out", type=Path, default=ROOT / "results" / "data" / "questions.md")
    args = ap.parse_args(argv)

    from think_reason_learn.rrf import RRF

    rows = list(csv.DictReader((args.answers / "questions.csv").open(encoding="utf-8")))
    m = {n: RRF.load(args.models / n) for n in ("c1a", "c1a40", "c1b", "c2")}
    kev = {q: i + 1 for i, q in enumerate(m["c2"].rules_)}
    if list(m["c2"].rules_) != json.loads((args.answers / "rules.json").read_text()):
        raise SystemExit("rules.json doesn't match C2's rules_")
    w_all, w_40 = weights(m["c1a"]), weights(m["c1a40"])
    vote = set(m["c1b"].rules_)
    rows.sort(key=lambda r: (kev.get(r["question"], 10**6), -float(r["f0.5"])))

    lines = [
        "# The questions",
        "",
        f"**In short:** Claude Opus 5.5 wrote **{len(rows)}** yes/no questions about the training "
        "founders (TRL's think step, B1). Kev-0.6B answered every one for every founder. Kev's "
        f"learn stages (C2, C3) read the **best {len(kev)}**, ranked by F0.5 on train; this page "
        "shows all of them and what each condition does with them. Generated by "
        "`research/questions_report.py` from `data/answers/questions.csv` and the saved TRL "
        "models; nothing is recomputed.",
        "",
        "## How to read the table",
        "",
        "- **Kev rank:** the question's place among the 40 Kev reads (C2, C3, CTRL and C1a-40 "
        "read the same 40), in the order Kev sees them. Blank: not among the 40.",
        "- **Precision, recall, F0.5 (train):** treating a *yes* answer as a prediction of "
        "success, on the training founders. 20% of founders succeed, so a precision above 0.20 "
        "means a yes makes success more likely. Terms: [GLOSSARY](../GLOSSARY.md).",
        "- **C1a weight, C1a-40 weight:** the elastic net's weight on the question's P(yes) "
        "(positive: a yes raises P(success)). Blank: weight zero, so the question isn't used.",
        "- **Vote:** ✓ if the paper's vote (C1b) counts it.",
        "- **Near-duplicates:** TRL keeps questions that ask nearly the same thing (for "
        "example ranks 3–5, all about an acquired prior startup). Their answers move together, "
        "so the elastic net splits weight between them, and one twin can get a negative weight "
        "that offsets another's positive one. Read near-duplicates' weights together, not one "
        "by one.",
        "",
        f"Counts: C1a uses {len(w_all)}, C1a-40 uses {len(w_40)}, C1b uses {len(vote)}, "
        f"Kev reads {len(kev)}.",
        "",
        "| Kev rank | Question | Precision | Recall | F0.5 | C1a weight | C1a-40 weight | Vote |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        q = r["question"]
        lines.append(
            f"| {kev.get(q, '')} | {q.replace('|', '/')} | {float(r['precision']):.2f} | "
            f"{float(r['recall']):.2f} | {float(r['f0.5']):.2f} | {fmt(w_all.get(q))} | "
            f"{fmt(w_40.get(q))} | {'✓' if q in vote else ''} |")
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {args.out} ({len(rows)} questions)")
    return 0


if __name__ == "__main__":
    sys.exit(main())

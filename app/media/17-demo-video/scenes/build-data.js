#!/usr/bin/env node
// Builds scenes/data.js from the voiceover alignment files and the clip meta files.
// Pages are opened with file://, where fetch() of local JSON is blocked, so the data is baked into a script.
// Rerun after the voiceover changes or after clips are recorded:  node scenes/build-data.js
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const script = JSON.parse(fs.readFileSync(path.join(root, 'script.json'), 'utf8'));
const MAX = 78; // characters per caption cue (wraps to at most two lines at the caption width)

function words(al) {
  const out = [];
  let cur = null;
  al.characters.forEach((ch, i) => {
    if (ch === ' ') { cur = null; return; }
    if (!cur) { cur = { w: '', s: al.character_start_times_seconds[i], e: 0 }; out.push(cur); }
    cur.w += ch;
    cur.e = al.character_end_times_seconds[i];
  });
  return out.map((w) => ({ w: w.w, s: +w.s.toFixed(3), e: +w.e.toFixed(3) }));
}

// Group words into cues: break at sentence ends, and at commas when the cue would get too long.
function cues(ws) {
  const clauses = [];
  let c = [];
  ws.forEach((w) => { c.push(w); if (/[.,?!:;]$/.test(w.w)) { clauses.push(c); c = []; } });
  if (c.length) clauses.push(c);
  const len = (a) => a.map((w) => w.w).join(' ').length;
  const out = [];
  let cur = [];
  const flush = () => { if (cur.length) out.push(cur); cur = []; };
  clauses.forEach((cl) => {
    if (len(cl) > MAX) { // a long clause: split by words
      flush();
      cl.forEach((w) => { if (len(cur.concat([w])) > MAX) flush(); cur.push(w); });
      if (/[.?!]$/.test(cl[cl.length - 1].w)) flush();
      return;
    }
    if (len(cur.concat(cl)) > MAX) flush();
    cur = cur.concat(cl);
    if (/[.?!]$/.test(cl[cl.length - 1].w)) flush();
  });
  flush();
  return out;
}

const voice = {};
script.sections.forEach((s) => {
  const al = JSON.parse(fs.readFileSync(path.join(root, 'voiceover', s.id + '.alignment.json'), 'utf8'));
  const ws = words(al);
  voice[s.id] = { text: s.text, cues: cues(ws) };
});

const clips = {};
const clipDir = path.join(root, 'clips');
if (fs.existsSync(clipDir)) {
  fs.readdirSync(clipDir).forEach((name) => {
    const dir = path.join(clipDir, name);
    if (!fs.statSync(dir).isDirectory()) return;
    const metaFile = path.join(dir, 'meta.json');
    const entry = { frames: 0, fps: 30, speed: 1, placeholder: fs.existsSync(path.join(dir, 'placeholder.png')) };
    if (fs.existsSync(metaFile)) {
      const m = JSON.parse(fs.readFileSync(metaFile, 'utf8'));
      // trust the files on disk over the count in meta.json if frames are missing
      let n = m.frames || 0;
      while (n > 0 && !fs.existsSync(path.join(dir, String(n).padStart(6, '0') + '.jpg'))) n--;
      entry.frames = n; entry.fps = m.fps || 30; entry.speed = m.speed || 1;
    }
    clips[name] = entry;
  });
}

const js = '// Generated by build-data.js. Do not edit by hand.\n' +
  'window.HM_VOICE = ' + JSON.stringify(voice) + ';\n' +
  'window.HM_CLIPS = ' + JSON.stringify(clips, null, 1) + ';\n';
fs.writeFileSync(path.join(__dirname, 'data.js'), js);
if (process.argv.includes('--print')) {
  Object.entries(voice).forEach(([id, v]) => {
    console.log('\n' + id);
    v.cues.forEach((c) => console.log('  [' + c[0].s + '-' + c[c.length - 1].e + '] ' + c.map((w) => w.w + '@' + w.s).join(' ')));
  });
}
console.log('data.js written:', Object.keys(voice).length, 'voice sections,', Object.keys(clips).length, 'clips');
